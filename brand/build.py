"""Build the AniEx wordmark and lockups from glyphs.json.

    python3 brand/build.py

Writes
  web/public/brand/<name>-light.svg, <name>-dark.svg   standalone files for posters and announcements
  web/src/components/brand/lockups.ts                  path data for BrandLockup.vue (ink = currentColor)

Construction (units: cap height = 750):
- The brand mark is the "A": its legs are exactly cap height and stand on the baseline. Inside the
  wordmark the star is scaled to 0.85 about its bottom point, so it still sits in the apex gap; the
  standalone mark (BrandMark.vue, favicon) keeps the full-size star.
- "niEx" is Geist 750, whose stems match the legs' thickness. The mark-to-n gap is the font's n-i
  spacing less 8%, for the open space above the slanted leg.
- 安易 is Noto Sans SC 650 (the same visual weight as Geist 750). Its ink, not its em box, is aligned:
  horizontal: ink from baseline to cap height; stacked: centred under the wordmark, 0.46 cap tall,
  half an em between the two characters; cn: mark + 安易, ink as tall as the legs.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
G = json.loads((ROOT / "brand" / "glyphs.json").read_text())
LAT, CJK = G["latin"]["glyphs"], G["cjk"]["glyphs"]

CAP = 750.0
STAR_K = 0.85
STAR = "M36 1 C37.12 9.4 39 11.65 46 13 C39 14.35 37.12 16.6 36 25 C34.88 16.6 33 14.35 26 13 C33 11.65 34.88 9.4 36 1 Z"
LEGL = "M27 25H35L21 58H12Z"
LEGR = "M37 25H45L53 58H44Z"
S = CAP / 33.0  # the legs span y 25..58 of the mark's 64 box


def r(v):
    return round(v, 1)


def glyph(table, ch, x, y, s):
    g = table[ch]
    k = round(s, 5)
    return f'<path class="ink" transform="translate({r(x)} {r(y)}) scale({k} {-k})" d="{g["d"]}"/>', g


def mark(x):
    star = f'<path class="ink" transform="translate(36 25) scale({STAR_K}) translate(-36 -25)" d="{STAR}"/>'
    body = (f'<g transform="translate({r(x - 12 * S)} {r(-58 * S)}) scale({round(S, 5)})">{star}'
            f'<path class="ink" d="{LEGL}"/><path class="red" d="{LEGR}"/></g>')
    return body, x + 41 * S


STAR_TOP = -(58 - 25 + 24 * STAR_K) * S


def wordmark():
    s = CAP / LAT["H"]["b"][3]
    body, xr = mark(0)
    n, i = LAT["n"], LAT["i"]
    gap = ((n["adv"] - n["b"][2]) + i["b"][0]) * s * 0.92
    x = xr + gap - n["b"][0] * s
    parts = [body]
    for ch in "niEx":
        p, g = glyph(LAT, ch, x, 0, s)
        parts.append(p)
        x += g["adv"] * s
    x_end = x - (LAT["x"]["adv"] - LAT["x"]["b"][2]) * s
    return "".join(parts), x_end, gap


def cjk_scale(height):
    a, e = CJK["安"], CJK["易"]
    y0, y1 = min(a["b"][1], e["b"][1]), max(a["b"][3], e["b"][3])
    return height / (y1 - y0), y0


def cjk(x, top, bottom, track=0.06):
    a, e = CJK["安"], CJK["易"]
    s, y0 = cjk_scale(bottom - top)
    baseline = bottom + y0 * s
    p1, _ = glyph(CJK, "安", x - a["b"][0] * s, baseline, s)
    x2 = x + (a["b"][2] - a["b"][0]) * s + 1000 * s * track
    p2, _ = glyph(CJK, "易", x2 - e["b"][0] * s, baseline, s)
    return p1 + p2, x2 + (e["b"][2] - e["b"][0]) * s


def cjk_width(height, track):
    a, e = CJK["安"], CJK["易"]
    s, _ = cjk_scale(height)
    return (a["b"][2] - a["b"][0]) * s + 1000 * s * track + (e["b"][2] - e["b"][0]) * s


def lockups():
    wm, x_end, gap = wordmark()
    out = {"wordmark": (wm, x_end, STAR_TOP, 0.0, "AniEx")}
    body, x1 = cjk(x_end + CAP * 0.55, -CAP, 0)
    out["horizontal"] = (wm + body, x1, STAR_TOP, 0.0, "AniEx 安易")
    h, gy, track = CAP * 0.46, CAP * 0.42, 0.5
    body, _ = cjk(x_end / 2 - cjk_width(h, track) / 2, gy, gy + h, track)
    out["stacked"] = (wm + body, x_end, STAR_TOP, gy + h, "AniEx 安易")
    m, xr = mark(0)
    body, x1 = cjk(xr + gap * 1.5, -CAP, 0)
    out["cn"] = (m + body, x1, STAR_TOP, 0.0, "安易")
    return out


THEMES = {"light": ("#17181C", "#C23A2B"), "dark": ("#EDE9E0", "#E0533F")}  # --ink / --brand per theme


def main():
    pub = ROOT / "web" / "public" / "brand"
    pub.mkdir(parents=True, exist_ok=True)
    ts = ["// Generated by brand/build.py. Do not edit.",
          "export interface Lockup { viewBox: string; width: number; height: number; label: string; body: string }",
          "export const lockups: Record<'wordmark' | 'horizontal' | 'stacked' | 'cn', Lockup> = {"]
    for name, (body, x1, top, bottom, label) in lockups().items():
        vb = f"0 {r(top)} {r(x1)} {r(bottom - top)}"
        for theme, (ink, red) in THEMES.items():
            svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="{label}">'
                   f'<style>.ink{{fill:{ink}}}.red{{fill:{red}}}</style>{body}</svg>\n')
            (pub / f"aniex-{name}-{theme}.svg").write_text(svg)
        web_body = body.replace('class="ink"', 'fill="currentColor"').replace('class="red"', 'style="fill:var(--brand)"')
        ts.append(f"  {name}: {{ viewBox: '{vb}', width: {r(x1)}, height: {r(bottom - top)}, label: '{label}', body: {json.dumps(web_body)} }},")
    ts.append("}")
    out = ROOT / "web" / "src" / "components" / "brand"
    out.mkdir(parents=True, exist_ok=True)
    (out / "lockups.ts").write_text("\n".join(ts) + "\n")
    print("wrote", pub, "and", out / "lockups.ts")


if __name__ == "__main__":
    main()
